def find_file(root, ensemble, exp, stats_filename):
    path = os.path.join(root, ensemble, exp, stats_filename)
    if os.path.exists(path):
        return path
    # try without ensemble folder if exp already contains ensemble
    alt = os.path.join(root, exp, stats_filename)
    if os.path.exists(alt):
        return alt
    return None


def build_experiment_lists(opts):
    """Return parallel lists (files, display_names) where display_name is ENSEMBLE:EXP."""
    if opts.files:
        files = [f.strip() for f in opts.files.split(',') if f.strip()]
        if not opts.names:
            sys.exit('ERROR: when using --files, must provide --names with ENSEMBLE:EXP display names')
        names = [n.strip() for n in opts.names.split(',') if n.strip()]
        if len(files) != len(names):
            sys.exit('ERROR: number of --files must match number of --names')
        return files, names

    # otherwise require root and bases; if experiments not provided, auto-discover
    if not (opts.root and opts.bases):
        sys.exit('ERROR: must supply either --files/--names OR --root and --base (and optionally --experiments)')

    ensemble_dirs = [b.strip() for b in opts.bases.split(',') if b.strip()]

    files = []
    names = []

    if opts.exps:
        exp_parts = [e.strip() for e in opts.exps.split(',') if e.strip()]
        for part in exp_parts:
            if ':' in part:
                ens, exp = [p.strip() for p in part.split(':', 1)]
                if ens not in ensemble_dirs:
                    print(f"Warning: ensemble {ens} not in supplied -b list; skipping {part}")
                    continue
                fpath = find_file(opts.root, ens, exp, opts.filename)
                if fpath is None:
                    print(f"Warning: file not found for {part}: expected under {opts.root}/{ens}/{exp}/{opts.filename}", file=sys.stderr)
                    continue
                files.append(fpath)
                names.append(f"{ens}:{exp}")
            else:
                # search across ensemble_dirs for this exp
                found = False
                for ens in ensemble_dirs:
                    fpath = find_file(opts.root, ens, part, opts.filename)
                    if fpath is not None:
                        files.append(fpath)
                        names.append(f"{ens}:{part}")
                        found = True
                        break
                if not found:
                    print(f"Warning: experiment {part} not found under any ensemble directories", file=sys.stderr)
    else:
        # Auto-discover experiments under each ensemble directory
        for ens in ensemble_dirs:
            ensemble_path = os.path.join(opts.root, ens)
            if not os.path.isdir(ensemble_path):
                print(f"Warning: ensemble directory not found: {ensemble_path}", file=sys.stderr)
                continue
            for item in sorted(os.listdir(ensemble_path)):
                exp_path = os.path.join(ensemble_path, item)
                if not os.path.isdir(exp_path):
                    continue
                fpath = os.path.join(exp_path, opts.filename)
                if os.path.exists(fpath):
                    files.append(fpath)
                    names.append(f"{ens}:{item}")

    if not files:
        sys.exit('ERROR: no experiment files resolved')
    return files, names


def extract_region_series(fname, variable, region_idx, change_mode=None):
    with Dataset(fname, 'r') as f:
        if 'daysSinceStart' not in f.variables:
            raise ValueError(f"Missing 'daysSinceStart' in {fname}")
        yr = np.asarray(f.variables['daysSinceStart'][:]) / 365.0
        yr = yr - yr[0]
        if variable not in f.variables:
            raise ValueError(f"Variable {variable} not found in {fname}")
        data = np.asarray(f.variables[variable][:])  # shape (nt, nRegions)
        # ensure 2D
        if data.ndim == 1:
            # single region file? treat as whole
            series = data.copy()
        else:
            if region_idx < 0 or region_idx >= data.shape[1]:
                raise IndexError(f"region index {region_idx} out of range for file {fname}")
            series = data[:, region_idx]
        if change_mode == 'absolute':
            series = series - series[0]
    return yr, series


def parse_region_indices(spec):
    """Parse a string like '0,2-5,7' into a sorted unique list of ints."""
    # Accept ints, iterables of ints, or the spec string
    if spec is None:
        return []
    if isinstance(spec, int):
        return [spec]
    if isinstance(spec, (list, tuple, np.ndarray)):
        return sorted({int(x) for x in spec})
    out = set()
    s = str(spec)
    parts = [p.strip() for p in s.split(',') if p.strip()]
    for part in parts:
        if '-' in part:
            lo, hi = part.split('-', 1)
            try:
                lo_i = int(lo)
                hi_i = int(hi)
            except ValueError:
                raise ValueError(f"Invalid range in region-indices: '{part}'")
            if hi_i < lo_i:
                raise ValueError(f"Invalid range {part}: high < low")
            for i in range(lo_i, hi_i + 1):
                out.add(i)
        else:
            try:
                out.add(int(part))
            except ValueError:
                raise ValueError(f"Invalid region index: '{part}'")
    return sorted(out)


def sanitize_name(s):
    """Make a short filesystem-safe string from a region name."""
    if s is None:
        return ''
    # replace spaces with underscore and remove path-unfriendly characters
    keep = []
    for ch in s:
        if ch.isalnum() or ch in ('-', '_'):
            keep.append(ch)
        elif ch.isspace():
            keep.append('_')
    res = ''.join(keep)
    # truncate to reasonable length
    return res[:40]


def get_scale_factor(units):
    """Return multiplicative factor to convert volume (m3) to requested units.

    Assumes the source data are volumes in m^3. For 'm3' -> 1.0, 'kg' -> m3 * rhoi,
    'Gt' -> m3 * rhoi / 1e12.
    """
    u = (units or '').lower()
    if u == 'm3' or u == 'm^3' or u == 'm**3':
        return 1.0
    if u == 'kg':
        return RHOI
    if u == 'gt' or u == 'g t' or u == 'giga' or u == 'gigaton' or u == 'gton':
        return RHOI / 1.0e12
    # default to Gt if unrecognised
    return RHOI / 1.0e12


def get_unit_string(variable, units):
    """Return a short unit string for axis labels based on variable and units."""
    if variable is None:
        return f' ({units})' if units else ''
    v = variable.lower()
    if 'volume' in v or 'vaf' in v:
        return f' ({units})'
    if 'area' in v:
        return ' (km^2)'
    # fallback
    return f' ({units})' if units else ''


def build_time_grid_and_matrix(files, variable, region_idx, change_mode=None):
    series_list = []
    time_arrays = []
    for fpath in files:
        try:
            yr, ser = extract_region_series(fpath, variable, region_idx, change_mode)
            yr = np.asarray(yr)
            ser = np.asarray(ser)
            time_arrays.append(yr)
            series_list.append(ser)
        except Exception as e:
            print(f"Warning: failed to read {fpath}: {e}", file=sys.stderr)
            time_arrays.append(np.array([]))
            series_list.append(np.array([]))

    if not any(len(t) for t in time_arrays):
        return np.array([]), np.empty((0, 0))
    all_times = np.unique(np.concatenate([t for t in time_arrays if len(t) > 0]))
    time_grid = np.sort(all_times)

    data_matrix = np.full((len(series_list), len(time_grid)), np.nan)
    for i, (t, s) in enumerate(zip(time_arrays, series_list)):
        if len(t) == 0 or len(s) == 0:
            continue
        if len(t) == 1:
            mask = np.isclose(time_grid, float(t[0]))
            if mask.any():
                data_matrix[i, mask] = float(s[0])
            continue
        try:
            from scipy.interpolate import interp1d
            interp = interp1d(t, s, kind='linear', bounds_error=False, fill_value=np.nan)
            data_matrix[i, :] = interp(time_grid)
        except Exception as e:
            print(f"Warning: interpolation failed for {files[i]}: {e}", file=sys.stderr)
    return time_grid, data_matrix


def plot_regional_time_series(time_grid, data_matrix, display_names, variable, unit_str):
    fig, ax = plt.subplots(1, 1, figsize=(12, 6))
    # build ensemble map from display names ENSEMBLE:EXP
    ensemble_map = {}
    for idx, dn in enumerate(display_names):
        ens = dn.split(':', 1)[0]
        ensemble_map.setdefault(ens, []).append(idx)

    palette = {}
    # assign colors per ensemble using tab10
    ens_names = list(ensemble_map.keys())
    # Allow an externally-specified mapping (set in `main()` as global ensemble_to_base_color)
    external = globals().get('ensemble_to_base_color', None)
    if external:
        for ens in ens_names:
            palette[ens] = external.get(ens, plt.cm.tab10(0))
    else:
        base = plt.cm.tab10(np.linspace(0, 1, max(1, len(ens_names))))
        for i, ens in enumerate(ens_names):
            palette[ens] = base[i % base.shape[0]]

    legend_handles = []
    legend_labels = []

    for ens, indices in ensemble_map.items():
        subset = data_matrix[indices, :]
        if subset.size == 0:
            continue
        with np.errstate(invalid='ignore'):
            pmin = np.nanmin(subset, axis=0)
            pmax = np.nanmax(subset, axis=0)
            p25 = np.nanpercentile(subset, 25, axis=0)
            p75 = np.nanpercentile(subset, 75, axis=0)
            mean_ts = np.nanmean(subset, axis=0)

        base_color = palette.get(ens)
        ax.fill_between(time_grid, pmin, pmax, color=base_color, alpha=0.08)
        ax.fill_between(time_grid, p25, p75, color=base_color, alpha=0.2)
        ax.plot(time_grid, mean_ts, color=base_color, linewidth=1.5, linestyle='--')

        from matplotlib.lines import Line2D
        legend_handles.append(Line2D([0], [0], color=base_color, lw=3))
        legend_labels.append(f"{ens} (n={len(indices)})")

    if legend_handles:
        ax.legend(legend_handles, legend_labels, loc='best')
    ax.set_xlabel('Time (years)')
    ax.set_ylabel(f'{variable}{unit_str}')
    ax.grid(True, alpha=0.3)
    plt.tight_layout()
    return fig


def plot_combined_metrics(time_grid, data_matrix, display_names, variable, unit_str):
    # 3 panels: top std, middle rel-std (σ/|mean| log), bottom kurtosis
    fig, axes = plt.subplots(3, 1, figsize=(10, 9), sharex=True)
    ensemble_map = {}
    for idx, dn in enumerate(display_names):
        ens = dn.split(':', 1)[0]
        ensemble_map.setdefault(ens, []).append(idx)

    palette = {}
    ens_names = list(ensemble_map.keys())
    # Allow externally provided mapping via global `ensemble_to_base_color`
    external = globals().get('ensemble_to_base_color', None)
    if external:
        for ens in ens_names:
            palette[ens] = external.get(ens, plt.cm.tab10(0))
    else:
        base = plt.cm.tab10(np.linspace(0, 1, max(1, len(ens_names))))
        for i, ens in enumerate(ens_names):
            palette[ens] = base[i % base.shape[0]]

    tiny = 1e-12
    ax0, ax1, ax2 = axes

    for ens, indices in ensemble_map.items():
        subset = data_matrix[indices, :]
        if subset.size == 0:
            continue
        with np.errstate(invalid='ignore', divide='ignore'):
            mean = np.nanmean(subset, axis=0)
            pmin = np.nanmin(subset, axis=0)
            pmax = np.nanmax(subset, axis=0)
            spread = pmax - pmin
            mean_abs = np.abs(mean)
            mean_safe = mean_abs.copy()
            mean_safe[mean_safe < tiny] = np.nan
            ratio = spread / mean_safe
            std_ts = np.nanstd(subset, axis=0)
            kurt_ts = stats.kurtosis(subset, axis=0, nan_policy='omit')

        base_color = palette.get(ens)
        ax0.plot(time_grid, std_ts, '-', color=base_color, linewidth=1.5, label=f"{ens} (n={len(indices)})")
        ax1.plot(time_grid, ratio, '-', color=base_color, linewidth=1.5)
        ax2.plot(time_grid, kurt_ts, '-', color=base_color, linewidth=1.5)

    ax0.set_ylabel('Standard Deviation (σ)')
    ax0.set_title(f'Ensemble standard deviation (σ) for {variable}')
    ax0.grid(True, alpha=0.3)

    ax1.set_ylabel('Std / |Mean|')
    ax1.set_yscale('log')
    ax1.set_title(f'σ / Δ{variable} — Std deviation (σ) / mean change in {variable} (log y-axis)')
    ax1.grid(True, alpha=0.3)

    ax2.set_ylabel('Kurtosis')
    ax2.set_xlabel('Time (years)')
    ax2.set_title(f'{variable} — Kurtosis over time')
    ax2.grid(True, alpha=0.3)

    # legend (one per ensemble) on top panel
    handles, labels = ax0.get_legend_handles_labels()
    if handles:
        ax0.legend(handles, labels, loc='best')

    plt.tight_layout()
    return fig


