def main():
    opts = parse_arguments()

    files, names = build_experiment_lists(opts)

    # Parse --ensemble-colors into a global mapping `ensemble_to_base_color`
    # so plotting functions can pick the colors per ensemble base.
    if getattr(opts, 'ensemble_colors', None):
        raw_colors = [c.strip() for c in opts.ensemble_colors.split(',') if c.strip()]
        # derive ensemble order from the display names (ENSEMBLE:EXP) in the files list
        ens_names = []
        for dn in names:
            ens = dn.split(':', 1)[0]
            if ens not in ens_names:
                ens_names.append(ens)

        # prefer ordering from --base if provided, otherwise use encountered order
        ensemble_order = []
        if getattr(opts, 'bases', None):
            try:
                base_list = [b.strip() for b in opts.bases.split(',') if b.strip()]
                for b in base_list:
                    if b in ens_names and b not in ensemble_order:
                        ensemble_order.append(b)
            except Exception:
                pass
        # append any ensembles not covered by -b
        for e in ens_names:
            if e not in ensemble_order:
                ensemble_order.append(e)

        ensemble_to_base_color = {}
        if len(raw_colors) == 0:
            pass
        else:
            for i, ens in enumerate(ensemble_order):
                ensemble_to_base_color[ens] = raw_colors[i % len(raw_colors)]

        # publish global mapping for plotting functions
        globals()['ensemble_to_base_color'] = ensemble_to_base_color
        print(f"Using ensemble colors: {ensemble_to_base_color}")

    # Read first file to get region names if needed
    # Read region names: prefer an external region-names file if provided,
    # otherwise read from the first regionalStats file if it contains 'regionNames'.
    rNames = None
    if getattr(opts, 'region_names_file', None):
        rn_file = opts.region_names_file
        if not os.path.exists(rn_file):
            sys.exit(f"ERROR: region names file not found: {rn_file}")
        with Dataset(rn_file, 'r') as f:
            if 'regionNames' in f.variables:
                raw = f.variables['regionNames'][:]
                rNames = []
                for r in range(raw.shape[0]):
                    try:
                        this = raw[r, :].tobytes().decode('utf-8').strip()
                    except Exception:
                        this = ''.join([c.decode('utf-8') for c in raw[r, :]])
                    rNames.append(this)
            else:
                sys.exit(f"ERROR: 'regionNames' not found in {rn_file}")
    else:
        first = files[0]
        with Dataset(first, 'r') as f:
            if 'regionNames' in f.variables:
                raw = f.variables['regionNames'][:]
                rNames = []
                for r in range(raw.shape[0]):
                    try:
                        this = raw[r, :].tobytes().decode('utf-8').strip()
                    except Exception:
                        this = ''.join([c.decode('utf-8') for c in raw[r, :]])
                    rNames.append(this)
            else:
                rNames = None

    # Map raw region names to human-friendly labels where available
    rNames_display = None
    if rNames is not None:
        # Build a cleaned alphanumeric key for each region name (similar to other scripts)
        rNamesOrig = [ ''.join(filter(str.isalnum, rn)) for rn in rNames ]

